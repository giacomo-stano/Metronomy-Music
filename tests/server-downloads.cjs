const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const exportsObject = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/serverDownloadState.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports: exportsObject, Map, Set, Promise });
const { ServerDownloadStore, serverState, serverLabel, isServerComplete } = exportsObject;
const track = { kind: 'track', id: '1', albumId: 'album1', title: 'Song', available: true };
const album = { kind: 'album', id: 'album1', title: 'Album', available: true };
const job = { id: 'job1', target: 'track:1', destination: 'giacomo', status: 'queued', created: 1, title: 'Song', message: '' };
(async () => {
  const store = new ServerDownloadStore();
  let calls = 0, finish, changes = 0;
  store.subscribe(() => changes++);
  const send = () => { calls++; return new Promise(resolve => { finish = resolve; }); };
  const first = store.enqueue(track, 'giacomo', send);
  assert.equal(first, store.enqueue(track, 'giacomo', send), 'double taps share a single POST');
  assert.equal(serverState(track, [], store.getSnapshot().pending), 'submitting');
  const staleVersion = store.version;
  await Promise.resolve(); finish(job); await first;
  assert.equal(calls, 1);
  assert.equal(store.getSnapshot().pending.length, 0);
  store.accept([], staleVersion);
  assert.equal(store.getSnapshot().jobs.length, 1, 'poll started before submission cannot erase the accepted job');
  const before = changes; store.accept([job]);
  assert.equal(changes, before, 'unchanged polling does not redraw the UI');
  store.accept([{ ...job, status: 'downloading' }]);
  assert.equal(serverState(track, store.getSnapshot().jobs, []), 'downloading');
  store.accept([{ ...job, status: 'completed' }]);
  assert.equal(store.getSnapshot().completion, 1);
  store.accept([{ ...job, status: 'completed' }]);
  assert.equal(store.getSnapshot().completion, 1, 'refresh catalogue once per completion, not on every poll');
  assert.equal(serverState(track, store.getSnapshot().jobs, []), 'completed');
  assert.equal(serverState({ ...track, libraryMatch: 'local' }, store.getSnapshot().jobs, []), 'present');
  assert.equal(serverState({ ...album, libraryMatch: 'local', libraryComplete: false }, [], []), 'partial');
  const partial = { ...album, libraryMatch: 'local', libraryComplete: false, libraryPresentCount: 2, libraryTotalCount: 3 };
  const complete = { ...partial, libraryComplete: true, libraryPresentCount: 3 };
  assert.equal(serverState(complete, [], []), 'present');
  assert.equal(isServerComplete({ ...partial, libraryComplete: true }), false, 'a stale complete flag cannot overrule partial counts');
  assert.equal(isServerComplete({ ...album, libraryMatch: 'local', libraryComplete: true }), false, 'old bridge metadata is not proof of completeness');
  assert.equal(serverLabel(partial, 'partial'), '2 / 3 brani sul server');
  assert.equal(serverLabel(complete, 'present'), '3 / 3 brani sul server');
  assert.equal(serverState({ ...album, libraryPresentCount: 0, libraryTotalCount: 3 }, [], []), 'partial');
  const albumJob = { ...job, target: 'album:album1', status: 'downloading' };
  assert.equal(serverState(partial, [albumJob], []), 'downloading', 'partial albums retain download animation');
  assert.equal(serverState(partial, [], ['album:album1|giacomo']), 'submitting');
  assert.equal(serverState(partial, [{ ...albumJob, status: 'completed' }], []), 'partial', 'job history never proves complete album ownership');
  assert.equal(serverState(album, [{ ...albumJob, status: 'completed' }], []), 'none', 'unknown inventory never shows a completion symbol');
  assert.equal(serverState(partial, [{ ...albumJob, status: 'failed' }], []), 'failed');
  assert.equal(serverState(track, [albumJob], []), 'downloading', 'album download covers its tracks by ID');
  assert.equal(serverState({ ...track, albumId: 'another' }, [albumJob], []), 'none', 'never infer ownership from a shared title');
  assert.equal(serverState(track, [job], [], 'lorenza'), 'none', 'destinations stay distinct');
  assert.equal(serverState(track, [{ ...job, status: 'failed' }], []), 'failed');
  assert.equal(serverState(track, [], ['album:album1|giacomo']), 'submitting');
  await assert.rejects(store.enqueue(track, 'giacomo', () => Promise.reject(Error('No space'))), /No space/);
  assert.equal(store.getSnapshot().pending.length, 0, 'failure clears the sending spinner');
  const otherAccount = new ServerDownloadStore();
  assert.equal(otherAccount.getSnapshot().jobs.length, 0, 'stores are isolated per account');
  let late;
  const unfinished = otherAccount.enqueue(track, 'lorenza', () => new Promise(resolve => { late = resolve; }));
  await Promise.resolve(); otherAccount.dispose(); late(job); await unfinished;
  assert.equal(otherAccount.getSnapshot().jobs.length, 0, 'late responses cannot publish after logout');
  const abandoned = new ServerDownloadStore();
  const request = abandoned.enqueue(track, 'giacomo', () => assert.fail('POST after logout'));
  abandoned.dispose(); await assert.rejects(request, /Account cambiato/);

  // Execute the real scroll-restoration initializer across player renders.
  const source = fs.readFileSync('src/LibraryScreen.tsx', 'utf8');
  const ast = ts.createSourceFile('LibraryScreen.tsx', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  let initializer;
  function visit(node) { if (ts.isVariableDeclaration(node) && node.name.getText(ast) === 'initialScrollOffset') initializer = node.initializer.getText(ast); ts.forEachChild(node, visit); }
  visit(ast); assert(initializer);
  let memo;
  const scrollOffsets = { current: { albums: 0 } };
  const context = { scrollOffsets, listKey: 'albums', grid: true, p: { resetKey: 0 }, useMemo: (fn, deps) => { if (!memo || deps.some((d, i) => d !== memo.deps[i])) memo = { deps, value: fn() }; return memo.value; } };
  const initial = vm.runInNewContext(initializer, context);
  for (let tick = 1; tick <= 100; tick++) {
    scrollOffsets.current.albums = tick * 25;
    assert.equal(vm.runInNewContext(initializer, context), initial, 'audio renders must never republish a scroll offset');
  }
  context.listKey = 'songs'; context.grid = false; vm.runInNewContext(initializer, context);
  context.listKey = 'albums'; context.grid = true;
  assert.equal(vm.runInNewContext(initializer, context).y, 2500, 'returning to the album list restores its saved position');
  scrollOffsets.current = {}; context.p.resetKey++;
  assert.equal(vm.runInNewContext(initializer, context).y, 0, 'explicit double tap resets saved offset');
  assert(source.includes('contentOffset={initialScrollOffset}'));
  for (const file of ['CatalogSearchResults', 'CatalogRows', 'CatalogBrowser', 'CatalogAlbumsPage', 'NetworkActions', 'PlayerSheet']) assert(fs.readFileSync('src/' + file + '.tsx', 'utf8').includes('ServerDownloadBadge'), file);
  const browser = fs.readFileSync('src/CatalogBrowser.tsx', 'utf8');
  assert(browser.includes('CatalogAlbumsPage') && browser.includes("group.id === 'album' ? () => onAlbums"));
  const albums = fs.readFileSync('src/CatalogAlbumsPage.tsx', 'utf8');
  assert(albums.includes('catalogQueue') && albums.includes('data.nextOffset') && albums.includes('ServerDownloadBadge'));
  console.log('Server downloads: shared state, duplicate/race guards, account isolation, completion, album badges, artist discography and stable scrolling passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
